import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { it } from 'vitest';
import { materialize } from '../../fixtures/materialize.js';
import type { ExpectedFinding } from '../../fixtures/spec.js';
import { ALL_SPECS } from '../../fixtures/specs/index.js';
import { ALL_RULES } from '../../src/rules/index.js';
import { scan } from '../../src/scan.js';
import { meetsThreshold, SEVERITIES, type Severity } from '../../src/severity.js';
import type { Finding } from '../../src/types.js';

// Phase 6 evaluation (npm run eval). Measures detection on the fixture corpus and
// what agentsapper reports on the benign corpus (npm run corpus:fetch first), and
// writes docs/evaluation/RESULTS.md and results.json.

const repoRoot = fileURLToPath(new URL('../..', import.meta.url));
const outDir = join(repoRoot, 'docs', 'evaluation');
const corpusDir = process.env.AGENTSAPPER_CORPUS ?? join(tmpdir(), 'agentsapper-corpus');
const FAIL_ON: Severity = 'high';

interface RuleTally {
  expected: number;
  detected: number;
  exactSeverity: number;
  unexpected: number;
}

const matches = (e: ExpectedFinding, f: Finding) =>
  e.ruleId === f.ruleId && e.file === f.file && (e.line === undefined || e.line === f.line);

function evaluateFixtures() {
  const perRule = new Map<string, RuleTally>(
    ALL_RULES.map((r) => [r.id, { expected: 0, detected: 0, exactSeverity: 0, unexpected: 0 }]),
  );
  const fixtures: Record<string, unknown>[] = [];
  let skipped = 0;
  for (const spec of ALL_SPECS) {
    let fixture;
    try {
      fixture = materialize(spec);
    } catch {
      skipped++;
      fixtures.push({
        id: spec.id,
        kind: spec.kind,
        skipped: 'symlinks not supported on this machine',
      });
      continue;
    }
    try {
      const result = scan(fixture.root);
      const unmatched = [...result.findings];
      let detected = 0;
      for (const e of spec.expect) {
        const tally = perRule.get(e.ruleId);
        if (tally === undefined) continue;
        tally.expected++;
        const i = unmatched.findIndex((f) => matches(e, f));
        if (i === -1) continue;
        detected++;
        tally.detected++;
        if (unmatched[i]?.severity === e.severity) tally.exactSeverity++;
        unmatched.splice(i, 1);
      }
      for (const f of unmatched) {
        const tally = perRule.get(f.ruleId);
        if (tally !== undefined) tally.unexpected++;
      }
      fixtures.push({
        id: spec.id,
        kind: spec.kind,
        source: spec.source,
        expected: spec.expect.length,
        detected,
        unexpected: unmatched.map((f) => `${f.ruleId} ${f.severity} ${f.file}:${f.line ?? '-'}`),
        incomplete: result.incomplete,
      });
    } finally {
      fixture.cleanup();
    }
  }
  return { perRule: Object.fromEntries(perRule), fixtures, skipped };
}

interface ManifestRepo {
  name: string;
  url: string;
  why: string;
  commit: string;
  checkout?: string;
}

function evaluateBenign() {
  const manifestPath = join(corpusDir, 'manifest.json');
  if (!existsSync(manifestPath)) return undefined;
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8')) as {
    fetchedAt: string;
    platform: string;
    repos: ManifestRepo[];
  };
  const repos = manifest.repos.map((repo) => {
    const started = Date.now();
    const result = scan(join(corpusDir, repo.name));
    const bySeverity = Object.fromEntries(
      SEVERITIES.map((s) => [s, result.findings.filter((f) => f.severity === s).length]),
    );
    return {
      ...repo,
      ms: Date.now() - started,
      bySeverity,
      failsAtDefault: result.findings.some((f) => meetsThreshold(f.severity, FAIL_ON)),
      incomplete: result.incomplete,
      errors: result.errors,
      findings: result.findings.map((f) => ({
        ruleId: f.ruleId,
        severity: f.severity,
        location: `${f.file}${f.line === undefined ? '' : `:${f.line}`}`,
        evidence: f.evidence,
      })),
    };
  });
  return { fetchedAt: manifest.fetchedAt, platform: manifest.platform, repos };
}

function markdown(
  fixtures: ReturnType<typeof evaluateFixtures>,
  benign: ReturnType<typeof evaluateBenign>,
): string {
  const out: string[] = [
    '# Evaluation results',
    '',
    `Generated by \`npm run eval\` with agentsapper's ${ALL_RULES.length} rules. Platform: ${process.platform}.`,
    '',
    '## Detection on the fixture corpus',
    '',
    `${ALL_SPECS.filter((s) => s.kind === 'malicious').length} malicious and ${ALL_SPECS.filter((s) => s.kind === 'benign').length} benign fixtures, each reproducing a published technique or a false-positive trap.` +
      (fixtures.skipped > 0
        ? ` ${fixtures.skipped} fixture(s) skipped on this machine (symlinks not supported).`
        : ''),
    'A detection counts when the rule reports the expected file (and line, where one is expected).',
    '',
    '| Rule | Status | Expected | Detected | Same severity | Unexpected |',
    '|---|---|---:|---:|---:|---:|',
  ];
  for (const rule of ALL_RULES) {
    const t = fixtures.perRule[rule.id] as RuleTally;
    out.push(
      `| ${rule.id} | ${rule.status} | ${t.expected} | ${t.detected} | ${t.exactSeverity} | ${t.unexpected} |`,
    );
  }

  const exploitPath = join(outDir, 'exploitability.json');
  if (existsSync(exploitPath)) {
    const exploit = JSON.parse(readFileSync(exploitPath, 'utf8')) as {
      run: string;
      environment: string;
      results: {
        spec: string;
        command: string;
        cwd: string;
        note: string;
        expectedExploit: boolean | string;
        exploited: boolean;
        detectedRules: string[];
        expectedRules: string[];
      }[];
    };
    out.push(
      '',
      '## Exploitability of the git fixtures',
      '',
      `Each case turns a fixture into a real repository and runs the git command the technique abuses, in a throwaway container (${exploit.environment}; [run](${exploit.run})). "Ran" means git executed the fixture's inert marker program.`,
      '',
      '| Fixture | Command | Expected | Ran | Detected by agentsapper | Note |',
      '|---|---|:---:|:---:|---|---|',
    );
    for (const r of exploit.results) {
      const expected =
        r.expectedExploit === true ? 'runs' : r.expectedExploit === false ? 'blocked' : 'recorded';
      const detected =
        r.detectedRules.length === r.expectedRules.length
          ? `yes (${r.detectedRules.join(', ')})`
          : `partial (${r.detectedRules.join(', ')})`;
      out.push(
        `| ${r.spec} | \`${r.command}\`${r.cwd === '.' ? '' : ` in \`${r.cwd}\``} | ${expected} | ${r.exploited ? 'yes' : 'no'} | ${detected} | ${r.note} |`,
      );
    }
  }

  if (benign === undefined) {
    out.push('', '_Benign corpus not fetched; run `npm run corpus:fetch` first._', '');
    return out.join('\n');
  }

  const failing = benign.repos.filter((r) => r.failsAtDefault);
  out.push(
    '',
    '## Benign corpus (false positives)',
    '',
    `${benign.repos.length} popular, legitimate repositories, shallow-cloned on ${benign.fetchedAt.slice(0, 10)} (${benign.platform}).`,
    `**${failing.length} of ${benign.repos.length}** would fail a CI gate at the default \`--fail-on ${FAIL_ON}\`.`,
    'Every finding below was reviewed by hand; see the README for the discussion.',
    '',
    '| Repository | Commit | Critical | High | Medium | Low | Info | Fails at high | Scan time |',
    '|---|---|---:|---:|---:|---:|---:|:---:|---:|',
  );
  for (const r of benign.repos) {
    const s = r.bySeverity as Record<Severity, number>;
    out.push(
      `| [${r.name}](${r.url}) | \`${r.commit.slice(0, 7)}\`${r.checkout === 'partial' ? ' (partial checkout)' : ''} | ${s.critical} | ${s.high} | ${s.medium} | ${s.low} | ${s.info} | ${r.failsAtDefault ? 'yes' : 'no'} | ${r.ms} ms |`,
    );
  }

  const ruleCounts = new Map<string, number>();
  for (const r of benign.repos)
    for (const f of r.findings)
      ruleCounts.set(
        `${f.ruleId} ${f.severity}`,
        (ruleCounts.get(`${f.ruleId} ${f.severity}`) ?? 0) + 1,
      );
  out.push(
    '',
    '### Findings on the benign corpus by rule and severity',
    '',
    '| Rule | Severity | Count |',
    '|---|---|---:|',
  );
  for (const [key, count] of [...ruleCounts].sort()) {
    const [rule, severity] = key.split(' ');
    out.push(`| ${rule} | ${severity} | ${count} |`);
  }

  out.push('', '### Findings at medium or above', '');
  for (const r of benign.repos) {
    const shown = r.findings.filter((f) => meetsThreshold(f.severity, 'medium'));
    if (shown.length === 0) continue;
    out.push(`- **${r.name}**`);
    for (const f of shown)
      out.push(
        `  - ${f.ruleId} ${f.severity} \`${f.location}\`: ${f.evidence.replaceAll('|', '\\|').replaceAll('`', "'")}`,
      );
  }
  const incomplete = benign.repos.filter((r) => r.incomplete.length > 0 || r.errors.length > 0);
  if (incomplete.length > 0) {
    out.push('', '### Incomplete scans', '');
    for (const r of incomplete)
      out.push(
        `- **${r.name}**: ${[...r.incomplete, ...r.errors.map((e) => `${e.ruleId}: ${e.message}`)].join('; ')}`,
      );
  }
  out.push('');
  return out.join('\n');
}

it('evaluates agentsapper against the fixture and benign corpora', () => {
  const fixtures = evaluateFixtures();
  const benign = evaluateBenign();
  mkdirSync(outDir, { recursive: true });
  writeFileSync(
    join(outDir, 'results.json'),
    `${JSON.stringify({ rules: ALL_RULES.length, fixtures, benign }, null, 2)}\n`,
  );
  writeFileSync(join(outDir, 'RESULTS.md'), markdown(fixtures, benign));
});
